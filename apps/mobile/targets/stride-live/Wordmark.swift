/// 워드마크 그림. 너비만 주면 높이는 비율대로(60 → 11.6)
struct Wordmark: View {
  let width: CGFloat
  let color: Color

  var body: some View {
    ZStack {
      WordmarkShape().fill(color)
      WordmarkPlusShape().fill(color, style: FillStyle(eoFill: true))
    }
    .frame(width: width, height: width * WordmarkShape.aspect)
    .accessibilityElement()
    .accessibilityLabel("STRIDE+")
  }
}

private func P(_ x: CGFloat, _ y: CGFloat) -> CGPoint { CGPoint(x: x, y: y) }
